import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { launchPreviewBrowser, openPreview, selectOption, assertFits } from './preview-browser.mjs';
const browser = await launchPreviewBrowser(), failures = [], results = [];
const destination = 'verification/fe-w30-contract-review';
try {
  const page = await openPreview(browser, '/photos',390,920,failures);
  await page.getByRole('button',{name:/^開啟照片：私人/}).click();
  await page.getByLabel('照片記錄原文',{exact:true}).fill('離線前整理的合成草稿');
  await page.getByRole('checkbox',{name:'我同意把原照片交由 Gemini 提取；候選仍需核對',exact:true}).click();
  await page.getByRole('button',{name:'預覽照片共享內容',exact:true}).click();
  await page.getByRole('checkbox',{name:'我確認原照片及這份記錄與孩子所屬家庭共享',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'確認照片及記錄家庭共享',exact:true}).isEnabled(),true);
  await page.getByRole('button',{name:'切換合成預覽情境',exact:true}).click();
  await page.getByRole('button',{name:'離線',exact:true}).click();
  await page.getByText('讀取未確認。原照片及草稿保留，先手動重新讀取。',{exact:true}).waitFor();
  assert.equal(await page.getByTestId('photo-shared-review').count(),0);
  assert.equal(await page.getByRole('checkbox',{name:'我同意把原照片交由 Gemini 提取；候選仍需核對',exact:true}).getAttribute('aria-checked'),'false');
  assert.equal(await page.getByLabel('照片記錄原文',{exact:true}).inputValue(),'離線前整理的合成草稿');
  await page.getByRole('button',{name:'一般',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'預覽照片共享內容',exact:true}).isDisabled(),true);
  await page.getByRole('button',{name:'重新讀取照片',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'預覽照片共享內容',exact:true}).isEnabled(),true);
  assert.equal(await page.getByLabel('照片記錄原文',{exact:true}).inputValue(),'離線前整理的合成草稿');
  await page.getByRole('button',{name:'預覽照片共享內容',exact:true}).click();
  assert.equal(await page.getByRole('checkbox',{name:'我確認原照片及這份記錄與孩子所屬家庭共享',exact:true}).getAttribute('aria-checked'),'false');
  assert.equal(await page.getByRole('button',{name:'確認照片及記錄家庭共享',exact:true}).isDisabled(),true);
  await assertFits(page,'photo reconnect 390');
  await page.screenshot({path:`destination-placeholder/photo-reconnect-390.png`.replace('destination-placeholder',destination)});
  results.push({photoReconnect:'raw retained; stale read blocks review; consents/review cleared; explicit reload and new confirmation required'});
  await page.getByRole('button',{name:'清除本頁',exact:true}).click();
  await page.getByRole('button',{name:'確認取代本頁',exact:true}).click();
  await page.getByRole('button',{name:'顯示照片情境',exact:true}).click();
  await selectOption(page,'照片情境','唯讀角色');
  await page.getByText('你目前可查看家庭共享照片及本人既有的私人照片；不能上傳、提取、確認或刪除。',{exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:/^開啟照片：私人/}).count(),1);
  assert.equal(await page.getByRole('button',{name:/^開啟照片：共享/}).count(),1);
  await page.getByRole('button',{name:/^開啟照片：私人/}).click();
  assert.equal(await page.getByTestId('photo-record-form').count(),0);
  assert.equal(await page.getByRole('button',{name:'刪除照片及連結記錄',exact:true}).count(),0);
  results.push({viewerPhotos:'own private and shared visible; record and delete actions absent'});
  await page.goto('http://localhost:8083/memory');
  await page.getByRole('button',{name:'示範 50+1 合成分頁',exact:true}).first().click();
  await page.getByText('已載入 50 項合成事實；仍有未載入頁面',{exact:false}).waitFor();
  await page.getByRole('button',{name:'載入更多事實',exact:true}).click();
  await page.getByText('已載入 51 項合成事實；本次合成清單已到最後一頁',{exact:false}).waitFor();
  await page.getByRole('tab',{name:'話題',exact:true}).click();
  await page.getByRole('button',{name:'載入更多話題',exact:true}).click();
  await page.getByText('已載入 51 項合成話題；本次合成清單已到最後一頁',{exact:false}).waitFor();
  await assertFits(page,'memory 51 items 390');
  results.push({memoryPages:'50+1 facts and topics append and terminal cursors clear'});
  await page.goto('http://localhost:8083/tasks');
  await page.getByRole('button',{name:'顯示情境工具',exact:true}).click();
  await selectOption(page,'任務情境','超過 50 項／分頁');
  await page.getByRole('button',{name:'載入更多事項',exact:true}).click();
  await page.getByText(/已載入 51 項/).waitFor();
  assert.equal(await page.getByRole('button',{name:'載入更多事項',exact:true}).count(),0);
  await assertFits(page,'tasks 51 items 390');
  results.push({taskPages:'50+1 append and final cursor clears'});
  await page.close();
  assert.deepEqual(failures,[]);
  await fs.writeFile(`${destination}/photo-pages-checks.json`,JSON.stringify({at:new Date().toISOString(),results,failures,scope:'local synthetic preview only'},null,2));
  console.log(JSON.stringify({passed:results.length,failures}));
} catch(error) {
  console.error(error.message);
  for(const page of browser.contexts().flatMap(context => context.pages())) await fs.writeFile('.expo-home/photo-pages-failure.txt',`${page.url()}\n${await page.locator('body').innerText()}`);
  process.exitCode=1;
} finally {await browser.close();}
