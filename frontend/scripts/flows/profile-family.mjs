import assert from "node:assert/strict";
import { resolve } from "node:path";
import { openPreview, assertFits, selectOption } from "../preview-browser.mjs";

export async function verifyProfile(browser, failures, directory) {
  const page = await openPreview(browser, "/profile", 320, 720, failures);
  await page.getByRole("button", { name: "查看較早版本", exact: true }).click();
  await page.getByRole("button", { name: "載入更早版本", exact: true }).click();
  await page.getByRole("textbox", { name: "約數年齡原值", exact: true }).fill(" 3 個半 ");
  await page.getByRole("textbox", { name: "確認或更正原因", exact: true }).fill("核對家長提供的約數");
  await page.getByRole("button", { name: "顯示情境工具", exact: true }).click();
  await selectOption(page, "模擬提交結果", "版本衝突");
  await page.getByRole("button", { name: "預覽家庭共享內容", exact: true }).click();
  await page.getByRole("button", { name: "我已核對，確認家庭共享", exact: true }).click();
  await page.getByText("比較版本 · 本次操作未保存", { exact: true }).waitFor();
  assert.equal(await page.getByRole("textbox", { name: "約數年齡原值", exact: true }).inputValue(), " 3 個半 ");
  await page.getByRole("button", { name: "已比較，使用最新基準", exact: true }).click();
  await selectOption(page, "模擬提交結果", "結果未知");
  await page.getByRole("button", { name: "預覽家庭共享內容", exact: true }).click();
  await page.getByRole("button", { name: "我已核對，確認家庭共享", exact: true }).click();
  await page.getByRole("heading", { name: "尚未確認操作結果", exact: true }).waitFor();
  assert.equal(await page.getByRole("textbox", { name: "約數年齡原值", exact: true }).isEditable(), false);
  const reference = await page.getByText("合成操作參考：", { exact: false }).textContent();
  await page.getByRole("button", { name: "查核原操作", exact: true }).click();
  await page.getByRole("heading", { name: "尚未確認操作結果", exact: true }).waitFor();
  assert.equal(await page.getByText("合成操作參考：", { exact: false }).textContent(), reference);
  await assertFits(page, "profile unknown 320");
  await page.screenshot({ path: resolve(directory, "profile-320-unknown.png") });
  await selectOption(page, "模擬查核結果", "已確認並讀回");
  await page.getByRole("button", { name: "查核原操作", exact: true }).click();
  await page.getByRole("heading", { name: "已保存", exact: true }).waitFor();
  await page.getByRole("button", { name: "永久刪除檔案及歷史", exact: true }).click();
  await page.getByRole("button", { name: "取消刪除", exact: true }).click();
  assert.equal(await page.getByRole("button", { name: "確認永久刪除檔案及歷史", exact: true }).count(), 0);
  await selectOption(page, "檔案情境", "唯讀角色");
  assert.equal(await page.getByRole("textbox", { name: "約數年齡原值", exact: true }).count(), 0);
  assert.equal(await page.getByRole("button", { name: "新增孩子", exact: true }).isEnabled(), false);
  await selectOption(page, "檔案情境", "權限失效");
  await page.getByText("孩子權限已失效", { exact: true }).waitFor();
  assert.equal(await page.getByRole("button", { name: "查核原操作", exact: true }).count(), 0);
  await page.close();
  return "profile: history/raw approximate age/conflict/same-operation lookup/deletion cancellation/role and permission cleanup at 320";
}

export async function verifyFamily(browser, failures, directory) {
  const page = await openPreview(browser, "/family", 1440, 992, failures);
  await page.getByRole("textbox", { name: "受邀人的電郵", exact: true }).fill("new-relative@example.test");
  await page.getByRole("button", { name: "核對邀請內容", exact: true }).click();
  assert.equal(await page.getByRole("button", { name: "再次確認操作", exact: true }).isEnabled(), false);
  const scope = page.getByRole("checkbox", { name: "我已核對目標及共享範圍", exact: true });
  await scope.focus(); await page.keyboard.press("Space");
  assert.equal(await scope.getAttribute("aria-checked"), "true");
  await page.getByRole("button", { name: "再次確認操作", exact: true }).click();
  await page.getByText("無效示例碼 · 只展示這一次", { exact: true }).waitFor();
  await page.getByRole("button", { name: "重新讀取家庭清單", exact: true }).click();
  assert.equal(await page.getByText("無效示例碼 · 只展示這一次", { exact: true }).count(), 0);
  const member = page.getByTestId("family-member-preview-caregiver");
  await selectOption(member, "新角色", "撤銷權限");
  await page.getByRole("button", { name: "更改陳爸爸權限", exact: true }).click();
  await page.getByRole("button", { name: "顯示家庭情境工具", exact: true }).click();
  await selectOption(page, "模擬提交結果", "結果未知");
  await scope.click();
  await page.getByRole("button", { name: "再次確認操作", exact: true }).click();
  await page.getByRole("heading", { name: "尚未確認操作結果", exact: true }).waitFor();
  assert.equal(await member.count(), 1, "An unknown revocation must not remove a member early");
  await selectOption(page, "模擬查核結果", "已確認並讀回");
  await page.getByRole("button", { name: "查核原操作", exact: true }).click();
  await page.getByRole("heading", { name: "已保存", exact: true }).waitFor();
  assert.equal(await member.count(), 0);
  await page.screenshot({ path: resolve(directory, "family-1440-revoked.png") });
  await selectOption(page, "本人視角", "檢視者");
  await page.getByText("只有擁有者可管理成員及邀請；此視角沒有這些管理操作或邀請電郵清單。", { exact: true }).waitFor();
  assert.equal(await page.getByRole("textbox", { name: "受邀人的電郵", exact: true }).count(), 0);
  await page.close();
  const narrow = await openPreview(browser, "/family", 320, 720, failures);
  await narrow.getByRole("textbox", { name: "收到的合成邀請碼", exact: true }).fill("PREVIEW-ONLY-INVALID-INCOMING");
  await narrow.getByRole("button", { name: "預覽收到的邀請", exact: true }).click();
  await narrow.getByRole("button", { name: "核對加入範圍", exact: true }).click();
  await assertFits(narrow, "family acceptance 320");
  await narrow.getByRole("checkbox", { name: "我已核對目標及共享範圍", exact: true }).click();
  await narrow.getByRole("button", { name: "再次確認加入", exact: true }).click();
  await narrow.getByRole("heading", { name: "已保存", exact: true }).waitFor();
  await narrow.screenshot({ path: resolve(directory, "family-320-acceptance.png") });
  await narrow.close();
  return "family: keyboard scope confirmation/one-time-code cleanup/unknown revocation/viewer boundary/invitation acceptance at 320";
}
