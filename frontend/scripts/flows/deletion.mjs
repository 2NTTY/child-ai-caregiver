import assert from "node:assert/strict";
import { resolve } from "node:path";
import { openPreview, assertFits, selectOption } from "../preview-browser.mjs";

export async function verifyDeletion(browser, failures, directory) {
  const page = await openPreview(browser, "/care", 320, 720, failures);
  await page.getByRole("button", { name: "查看睡眠記錄", exact: true }).click();
  await page.getByRole("button", { name: "永久刪除此記錄及歷史", exact: true }).click();
  const scope = page.getByRole("checkbox", { name: "我明白會永久刪除此記錄及全部歷史", exact: true });
  const submit = page.getByRole("button", { name: "確認並模擬永久刪除記錄", exact: true });
  assert.equal(await submit.isDisabled(), true);
  await page.getByRole("button", { name: "顯示情境工具", exact: true }).click();
  await selectOption(page, "模擬提交結果", "失敗");
  await scope.focus(); await page.keyboard.press("Space");
  assert.equal(await scope.getAttribute("aria-checked"), "true");
  await submit.click();
  await page.getByText("模擬失敗：已知沒有刪除。", { exact: false }).waitFor();
  assert.equal(await scope.getAttribute("aria-checked"), "false");
  await selectOption(page, "模擬提交結果", "版本衝突");
  await scope.click(); await submit.click();
  await page.getByRole("button", { name: "已比較，使用最新刪除基準", exact: true }).waitFor();
  assert.equal(await submit.isDisabled(), true);
  await page.getByRole("button", { name: "已比較，使用最新刪除基準", exact: true }).click();
  assert.equal(await scope.getAttribute("aria-checked"), "false");
  await selectOption(page, "模擬提交結果", "結果未知");
  await scope.click(); await submit.click();
  await page.getByRole("button", { name: "模擬查核原操作", exact: true }).waitFor();
  const reference = await page.getByText("合成操作參考：", { exact: false }).textContent();
  assert.equal(await submit.isDisabled(), true);
  assert.equal(await page.getByRole("button", { name: "取消刪除記錄", exact: true }).isDisabled(), true);
  await page.getByRole("button", { name: "模擬查核原操作", exact: true }).click();
  await page.getByRole("button", { name: "模擬查核原操作", exact: true }).waitFor();
  assert.equal(await page.getByText("合成操作參考：", { exact: false }).textContent(), reference);
  await assertFits(page, "record deletion unknown 320");
  await page.screenshot({ path: resolve(directory, "care-320-deletion-unknown.png") });
  await selectOption(page, "模擬查核結果", "已保存");
  await page.getByRole("button", { name: "模擬查核原操作", exact: true }).click();
  await page.getByText("已確認刪除（預覽）", { exact: true }).waitFor();
  assert.equal(await page.getByRole("button", { name: "查看睡眠記錄", exact: true }).count(), 0);
  await selectOption(page, "記錄情境", "唯讀角色");
  await page.getByRole("button", { name: "查看睡眠記錄", exact: true }).click();
  assert.equal(await page.getByRole("button", { name: "永久刪除此記錄及歷史", exact: true }).count(), 0);
  await page.close();

  const child = await openPreview(browser, "/profile", 390, 844, failures);
  await child.getByRole("button", { name: "刪除整位孩子（預覽）", exact: true }).click();
  const acknowledge = child.getByRole("checkbox", { name: "我明白會永久刪除小昕及全部關聯資料", exact: true });
  const remove = child.getByRole("button", { name: "確認並模擬刪除整位孩子", exact: true });
  assert.equal(await child.getByRole("textbox", { name: "過敏資料（可空）", exact: true }).isEditable(), false);
  await selectOption(child, "模擬提交結果", "失敗");
  await acknowledge.click(); await remove.click();
  await child.getByLabel("操作狀態：失敗", { exact: true }).waitFor();
  assert.equal(await child.getByRole("button", { name: "切換至小昕", exact: true }).count(), 1);
  await child.getByRole("button", { name: "重新核對刪除範圍", exact: true }).click();
  assert.equal(await acknowledge.getAttribute("aria-checked"), "false");
  await selectOption(child, "模擬提交結果", "結果未知");
  await acknowledge.click(); await remove.click();
  await child.getByLabel("操作狀態：結果未知", { exact: true }).waitFor();
  assert.equal(await child.getByRole("button", { name: "切換至小昕", exact: true }).count(), 1);
  assert.equal(await child.getByRole("button", { name: "取消刪除孩子", exact: true }).isDisabled(), true);
  await selectOption(child, "模擬查核結果", "已保存");
  await child.getByRole("button", { name: "模擬查核原操作", exact: true }).click();
  await child.getByRole("button", { name: "切換至阿樂", exact: true }).waitFor();
  await child.getByText("已模擬移除孩子", { exact: false }).waitFor();
  assert.equal(await child.getByRole("button", { name: "切換至小昕", exact: true }).count(), 0);
  assert.equal(await child.getByRole("button", { name: "刪除整位孩子（預覽）", exact: true }).count(), 0, "Caregiver must not get owner deletion");
  await assertFits(child, "child deletion 390");
  await child.screenshot({ path: resolve(directory, "profile-390-child-deleted.png") });
  await child.close();
  return "deletion: record scope/checkbox keyboard/failure/explicit conflict review/same-operation lookup/owner-only child deletion/isolation";
}
