import assert from "node:assert/strict";
import { resolve } from "node:path";
import { openPreview, assertFits, selectOption } from "../preview-browser.mjs";

async function channelsPage(browser, failures, width = 1440) {
  const page = await openPreview(browser, "/settings", width, width < 400 ? 844 : 992, failures);
  await page.getByRole("tab", { name: "通知渠道", exact: true }).click();
  return page;
}
async function approve(scope, label) {
  const checkbox = scope.getByRole("checkbox", { name: label, exact: true });
  await checkbox.focus(); await checkbox.press("Space");
  assert.equal(await checkbox.getAttribute("aria-checked"), "true");
}
const submit = scope => scope.getByRole("button", { name: "模擬確認這項渠道操作", exact: true }).click();
const reference = scope => scope.getByText("合成操作參考：", { exact: false }).textContent();

