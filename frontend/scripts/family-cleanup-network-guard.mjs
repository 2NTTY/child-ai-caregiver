import net from 'node:net';
import tls from 'node:tls';
import http from 'node:http';
import https from 'node:https';
import dns from 'node:dns';
import dgram from 'node:dgram';
import {syncBuiltinESMExports} from 'node:module';
let attempts=0;
const deny=name=>(...args)=>{ attempts++; throw new Error('NETWORK_DISABLED_FOR_REVIEW: '+name); };
globalThis.fetch=deny('global.fetch');
net.Socket.prototype.connect=deny('net.Socket.connect');
net.connect=net.createConnection=deny('net.connect');
tls.connect=deny('tls.connect');
http.request=http.get=deny('http.request');
https.request=https.get=deny('https.request');
dns.lookup=dns.resolve=deny('dns');
dgram.createSocket=deny('dgram.createSocket');
syncBuiltinESMExports();
process.on('exit',()=>{ console.log(JSON.stringify({networkGuard:'fetch/socket/http/tls/dns/dgram tripwire; in-memory injected fetch only',blockedAttempts:attempts})); if(attempts)process.exitCode=1; });
