const fs=require('node:fs'),assert=require('node:assert/strict');
const {JSDOM}=require('../caregiver_mermaid/node_modules/jsdom');
const w=new JSDOM(fs.readFileSync(process.argv[2],'utf8'),{runScripts:'outside-only'}).window,d=w.document;
const el=d.querySelector('#image-dialog'),img=d.querySelector('#image-full');
Object.assign(w.HTMLDialogElement.prototype,{showModal(){this.open=true},close(){this.open=false;this.dispatchEvent(new w.Event('close'))}});
el.getBoundingClientRect=()=>({left:10,top:20,right:190,bottom:180});
w.eval(d.scripts[1].textContent);
assert.equal(el.querySelector('button'),null,'no visible close button');
const p=d.querySelector('button.image-preview');p.focus();p.click();
assert(el.open);assert.equal(d.activeElement,d.querySelector('#image-title'));
const signal=(node,type,x=7,y=5)=>node.dispatchEvent(new w.MouseEvent(type,{bubbles:true,cancelable:true,clientX:x,clientY:y,button:0}));
signal(img,'pointerdown',40,40);signal(img,'click',40,40);assert(el.open,'clicking the image stays open');
signal(el,'pointerdown',40,40);signal(el,'click',40,40);assert(el.open,'padding inside stays open');
signal(img,'pointerdown',40,40);signal(el,'click');assert(el.open,'drag starting inside does not close');
signal(el,'pointerdown');signal(el,'pointercancel');signal(el,'click');assert(el.open,'canceled pointer does not close');
signal(el,'pointerdown');signal(el,'click');assert(!el.open,'outside click closes');assert.equal(d.activeElement,p);
p.click();el.dispatchEvent(new w.Event('cancel',{cancelable:true}));assert(!el.open,'Escape still closes');assert.equal(d.activeElement,p);
assert.equal(d.querySelector('#summary').textContent,'我的選擇（0）');
console.log('PASS backdrop, image and padding, drag, cancel, focus, Escape');
